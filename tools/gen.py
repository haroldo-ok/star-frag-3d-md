#!/usr/bin/env python3
"""Star Frag 3D (Mega Drive) asset generator: writes gen/*.c, gen/*.s, gen/assets.h
and res/*.res (+ WAV / VGM) from the Brutal Doom pk3, the skins WAD and the
procedural art.  Run from anywhere:  python3 -I tools/gen.py"""
import sys, os, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import *
import world, sprites, ui, audio
from maps import ARENAS

def main(parts):
    t0 = time.time()
    h = ['/* generated by tools/gen.py - do not edit */', '#ifndef ASSETS_H', '#define ASSETS_H', '#include "gfxdefs.h"']
    if 'world' in parts:
        src, tex_src, n = world.gen_arenas()
        write(os.path.join(GEN, 'arenas.c'), src)
        write(os.path.join(GEN, 'textures.c'), tex_src)
        write(os.path.join(GEN, 'tables.c'), world.gen_tables())
        write(os.path.join(GEN, 'scalers.s'), world.gen_scalers())
        print('world done %.1fs' % (time.time() - t0))
    if 'sprites' in parts or 'ui' in parts:
        src, info = sprites.gen_all()
        gp = info['gpal']
        src += c_u32('font_tiles', ui.gen_fonts(gp))
        src += c_u32('bigdig_tiles', ui.gen_bigdigits(gp))
        pdata, npanel = ui.gen_panel(gp)
        src += c_u32('panel_tiles', pdata)
        src += c_u32('arrow_tiles', ui.gen_arrows(gp))
        src += c_u32('radar_tiles', ui.gen_radar(gp))
        src += c_u32('grad_tiles', world.gen_gradient_tiles())
        tdata, tmap, tpal, ntt = ui.gen_title()
        src += c_u32('title_tiles', tdata)
        src += c_arr('title_map', tmap, 'u16', per=40)
        src += c_arr('title_pal', tpal, 'u16', per=16)
        write(os.path.join(GEN, 'gfx.c'), src)
        print('sprites/ui done %.1fs (sprite data %d KB, max tiles %d, title tiles %d)' %
              (time.time() - t0, info['total'] // 1024, info['maxtiles'], ntt))
        names = [n for n, _ in sprites.ITEMS + sprites.EXTRA]
        for i, n in enumerate(names):
            h.append('#define G_%s %d' % (n, i))
        h.append('#define G_SKIN0 %d' % len(names))
        h.append('#define NSKINGFX %d' % sprites.NSKINGFX)
        h.append('#define NSKINS %d' % len(sprites.SKINS))
        h.append('#define NGFX %d' % (len(names) + sprites.NSKINGFX * len(sprites.SKINS)))
        h.append('#define NLEVELS_SZ %d' % sprites.NLEVELS)
        h.append('#define NPANEL_TILES %d' % npanel)
        h.append('#define NTITLE_TILES %d' % ntt)
        h.append('#define NWEAPONS %d' % len(sprites.WEAPONS))
        h.append('#define WPN_MAXTILES %d' % sprites.WPN_MAXTILES)
    if 'audio' in parts:
        res = '# generated by tools/gen.py\n'
        r, n = audio.gen_sfx()
        res += r
        res += audio.gen_music()
        write(os.path.join(RES, 'sound.res'), res)
        t = '/* generated by tools/gen.py */\n#include <genesis.h>\n#include "sound.h"\n'
        t += 'const u8 * const sfx_data[] = { 0, %s };\n' % ', '.join('sfx_%s' % x[0].lower() for x in audio.SFX)
        t += 'const u32 sfx_len[] = { 0, %s };\n' % ', '.join('sizeof(sfx_%s)' % x[0].lower() for x in audio.SFX)
        t += 'const u8 * const mus_data[] = { %s };\n' % ', '.join('mus_%s' % m[0] for m in audio.MUSIC)
        write(os.path.join(GEN, 'soundtab.c'), t)
        print('audio done %.1fs (sfx %d KB)' % (time.time() - t0, n // 1024))
    h.append('#define NARENAS %d' % len(ARENAS))
    sfx = ['SFX_%s' % s[0] for s in audio.SFX]
    h.append('enum { SFX_NONE, %s, NSFX };' % ', '.join(sfx))
    h.append('#define NSONGS %d' % len(audio.MUSIC))
    h.append('enum { %s };' % ', '.join('MUS_%s' % m[0].upper() for m in audio.MUSIC))
    h.append('#endif')
    if 'sprites' in parts or 'ui' in parts:
        write(os.path.join(GEN, 'assets.h'), '\n'.join(h) + '\n')

if __name__ == '__main__':
    main(sys.argv[1:] or ['world', 'sprites', 'ui', 'audio'])
